export function normalizeDepartmentName(rawName) {
  const trimmed = String(rawName || '').trim();
  if (!trimmed) return 'ฝ่ายสถานที่';
  const withoutPrefix = trimmed.replace(/^ฝ่าย/, '').trim();
  if (LEGACY_DEPT_MAP[withoutPrefix]) {
    return LEGACY_DEPT_MAP[withoutPrefix];
  }
  return trimmed.startsWith('ฝ่าย') ? trimmed : `ฝ่าย${withoutPrefix}`;
}

export function stripDepartmentPrefix(rawName) {
  return normalizeDepartmentName(rawName).replace(/^ฝ่าย/, '').trim();
}
